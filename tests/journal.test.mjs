import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { URL } from 'node:url';
import { ARTICLES, categories, related, getArticle } from '../src/content/journal.js';
import { IMAGES } from '../src/content/images.js';
import { PORTFOLIO_IMAGES } from '../src/content/portfolioImages.js';
import { PROJECTS } from '../src/content/projects.js';
import { SERVICES } from '../src/content/services.js';

const pub = PROJECTS.filter((p) => p.published);
const imagesOf = (a) => [a.image, ...a.body.flatMap((b) => (b.t === 'figure' ? [b.image] : b.t === 'pair' ? b.items.map((i) => i.image) : []))];
const text = (a) => [a.title, a.excerpt, ...a.body.map((b) => b.x || '')].join(' ');

test('twelve published stories with unique slugs and the four layouts', () => {
  assert.equal(ARTICLES.length, 12); assert.equal(new Set(ARTICLES.map((a) => a.slug)).size, 12);
  assert.ok(ARTICLES.every((a) => a.published && getArticle(a.slug)));
  assert.deepEqual([...new Set(ARTICLES.map((a) => a.layout))].sort(), ['classic', 'immersive', 'plate', 'split']);
  assert.equal(ARTICLES.filter((a) => a.featured).length, 1); assert.ok(categories().length >= 5 && categories().length <= 7);
});
test('every article image resolves in the registry and to a real file; none is reused', () => {
  const all = ARTICLES.flatMap(imagesOf);
  assert.equal(new Set(all).size, all.length, 'an image is used twice');
  for (const id of all) {
    const m = IMAGES[id] || PORTFOLIO_IMAGES[id]; assert.ok(m, `no registry entry for ${id}`);
    const base = (m.src || m.file || `/img/${id}`).toString();
    assert.ok(existsSync(new URL(`../public/img/${id}-1400.webp`, import.meta.url)) || existsSync(new URL(`../public/img/${id}-800.webp`, import.meta.url)) || id.startsWith('portfolio/'), `missing files for ${id} (${base})`);
  }
  for (const a of ARTICLES) assert.ok(imagesOf(a).length >= 3 && imagesOf(a).length <= 5, `${a.slug} has ${imagesOf(a).length} images`);
});
test('no old cartoon-style legacy image ids, and none used outside the portfolio set', () => {
  const legacy = ['villa-dusk', 'villa-pool', 'villa-detail', 'tower-low', 'tower-plaza', 'civic-front', 'civic-aerial', 'interior-living', 'interior-stair', 'landscape-garden', 'landscape-pavilion', 'resort-hill', 'facade-fins', 'studio-model'];
  for (const a of ARTICLES) for (const id of imagesOf(a)) assert.ok(!legacy.includes(id), `${a.slug} uses ${id}`);
});
test('references: every linked project and service exists and is published', () => {
  for (const a of ARTICLES) { for (const p of a.projects) assert.ok(pub.some((x) => x.slug === p), `${a.slug} → ${p}`); for (const s of a.services) assert.ok(SERVICES.some((x) => x.slug === s), `${a.slug} → ${s}`); }
});
test('every project the text names exists (exact title, no invented project names)', () => {
  const norm = (t) => t.replace(/^The /, '').replace(/ Study$/, '').trim(), titles = new Set(pub.map((p) => norm(p.title)));
  const mention = /\b((?:(?:[A-Z][A-Za-zç’'-]+|of) ){1,6}?)(?:interior )?study\b/g; let n = 0;
  for (const a of ARTICLES) for (const m of text(a).matchAll(mention)) {
    const name = norm(m[1].trim().replace(/^(?:The|Our|In|Executive Office interior)\s+/, (x) => (x.startsWith('Executive') ? x : '')).replace(/^(The|Our|In) /, ''));
    if (/^(One|The studio|This|That)$/.test(name)) continue; n++; assert.ok(titles.has(name), `${a.slug}: "${name}" is not a portfolio project title`);
  }
  assert.ok(n >= 30, `only ${n} project mentions were checked`);
});
test('editorial hygiene: no banned buzzwords, no AI labels, no placeholder wording', () => {
  const banned = /\b(revolutionary|seamless(ly)?|transformative|timeless|innovative|game-?changing|cutting-edge|world-class)\b/i, labels = /\b(AI[- ]generated|generated by AI|AI image|AI concept|placeholder|lorem ipsum|illustrative placeholder)\b/i;
  for (const a of ARTICLES) { const t = text(a); assert.ok(!banned.test(t), `${a.slug}: ${t.match(banned)?.[0]}`); assert.ok(!labels.test(t + JSON.stringify(a))); assert.ok(!a.demo); }
});
test('each story is substantial and has headings; related stories are real', () => {
  for (const a of ARTICLES) { const words = a.body.filter((b) => b.t === 'p').map((b) => b.x).join(' ').split(/\s+/).length; assert.ok(words >= 450, `${a.slug} ${words}`); assert.ok(a.body.filter((b) => b.t === 'h2').length >= 3); assert.ok(related(a, 3).length >= 1); assert.ok(a.excerpt.length > 60); }
});
